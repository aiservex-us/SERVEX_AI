'use client';

import React, { useEffect, useState } from 'react';
import { supabase } from '../../../../lib/supabaseClient';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { Bot, Sparkles, Zap, FileText, Shield, Cloud, RefreshCw } from 'lucide-react';

const AgentInfo = () => {
  const [agentData, setAgentData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [isVisible, setIsVisible] = useState(false);

  useEffect(() => {
    const fetchAgentInfo = async () => {
      try {
        setLoading(true);
        const { data, error: supabaseError } = await supabase
          .from('ClientsSERVEX_General_Procces')
          .select('informa_agent_raw')
          .maybeSingle();

        if (supabaseError) throw supabaseError;
        setAgentData(data?.informa_agent_raw || null);
      } catch (err) {
        console.error('Fetch log:', err.message);
        setAgentData(null);
      } finally {
        setLoading(false);
        setTimeout(() => setIsVisible(true), 50);
      }
    };

    fetchAgentInfo();
  }, []);

  if (loading) {
    return (
      <div className="flex flex-col items-center justify-center min-h-[60vh] bg-transparent font-sans">
        <div className="relative mb-6">
          <div className="w-16 h-16 rounded-full border-4 border-white/15 border-t-white animate-spin" />
          <div className="absolute inset-0 flex items-center justify-center">
            <Bot size={20} className="text-white" />
          </div>
        </div>
        <p className="text-zinc-300 font-bold text-[10px] uppercase tracking-[0.25em] animate-pulse">
          Synchronizing with SVX_AI...
        </p>
        <div className="mt-6 flex gap-1.5">
          {[0, 1, 2, 3, 4].map(i => (
            <div
              key={i}
              className="w-1.5 h-1.5 rounded-full bg-white/40"
              style={{ animation: `pulse 1.4s ease-in-out ${i * 0.2}s infinite` }}
            />
          ))}
        </div>
      </div>
    );
  }

  if (!agentData) {
    return (
      <div className="flex items-center justify-center min-h-[70vh] px-4 font-sans bg-transparent">
        <div
          className="max-w-md w-full bg-[#09090b]/85 backdrop-blur-2xl border border-white/10 rounded-2xl shadow-[0_20px_50px_rgba(0,0,0,0.8),inset_0_1px_0_0_rgba(255,255,255,0.08)] p-10 text-center text-zinc-100"
          style={{ animation: 'fadeInUp 0.4s ease forwards' }}
        >
          <div className="flex justify-center mb-6">
            <div className="relative">
              <div className="absolute inset-0 rounded-full bg-white/10 animate-ping opacity-50" />
              <div className="relative bg-white/5 w-20 h-20 rounded-2xl flex items-center justify-center border border-white/10 shadow-inner">
                <Bot size={32} className="text-zinc-400" />
              </div>
            </div>
          </div>

          <div className="inline-flex items-center gap-1.5 bg-amber-500/10 border border-amber-500/20 px-3 py-1 rounded-full mb-4">
            <div className="w-1.5 h-1.5 rounded-full bg-amber-400 animate-pulse" />
            <span className="text-[9px] font-bold uppercase tracking-[0.2em] text-amber-300">Pending Analysis</span>
          </div>

          <h3 className="text-white text-[12px] font-bold uppercase tracking-[0.2em] mb-2">
            Audit in Progress
          </h3>
          <p className="text-zinc-400 text-[11px] leading-relaxed mb-6 px-4 font-normal">
            No audit information has been generated by the AI models for this record yet.
            Please check back once the analysis process is complete.
          </p>

          <button
            onClick={() => window.location.reload()}
            className="inline-flex items-center gap-2 px-6 py-2.5 bg-white text-zinc-950 text-[10px] font-bold uppercase tracking-[0.15em] rounded-xl hover:bg-zinc-200 active:scale-[0.98] transition-all shadow-sm group cursor-pointer"
          >
            <RefreshCw size={12} className="group-hover:rotate-180 transition-transform duration-500" />
            Update Report
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="bg-transparent min-h-screen py-8 px-2 sm:px-4 font-sans text-zinc-100">
      <div
        className="max-w-5xl mx-auto bg-[#09090b]/85 backdrop-blur-2xl rounded-2xl shadow-[0_20px_50px_rgba(0,0,0,0.8),inset_0_1px_0_0_rgba(255,255,255,0.08)] border border-white/10 overflow-hidden"
        style={{ opacity: isVisible ? 1 : 0, transform: isVisible ? 'translateY(0)' : 'translateY(12px)', transition: 'opacity 0.45s ease, transform 0.45s ease' }}
      >

        {/* Header */}
        <div className="bg-white/[0.03] border-b border-white/10 p-5 flex items-center justify-between">
          <div className="flex items-center gap-4">
            <div className="w-9 h-9 bg-white/10 rounded-xl flex items-center justify-center border border-white/20 shadow-sm">
              <Bot size={16} className="text-white" />
            </div>
            <div>
              <div className="flex items-center gap-2 mb-0.5">
                <h1 className="text-white font-bold text-[12px] leading-none tracking-tight">Console Executive Report</h1>
                <div className="flex items-center gap-1 bg-white/10 px-1.5 py-0.5 rounded-full border border-white/10">
                  <Zap size={8} className="text-amber-400 fill-amber-400" />
                  <span className="text-[8px] font-bold text-white/90 tracking-wider">v4.10</span>
                </div>
              </div>
              <p className="text-zinc-400 text-[9px] uppercase tracking-[0.2em] mt-1 font-bold">Engineering Audit</p>
            </div>
          </div>
          <div className="flex items-center gap-3">
            <div className="hidden sm:flex items-center gap-1.5 px-2.5 py-1 bg-white/10 border border-white/15 rounded-lg text-[8px] font-bold text-zinc-300 uppercase tracking-wider">
              <Sparkles size={9} className="text-amber-300" />
              SVX_PROD
            </div>
            <div className="flex items-center gap-2 px-3 py-1 bg-emerald-500/10 border border-emerald-500/20 rounded-lg">
              <div className="w-1.5 h-1.5 bg-emerald-400 rounded-full animate-pulse" />
              <span className="text-emerald-300 text-[9px] font-bold uppercase tracking-widest">Live Data</span>
            </div>
          </div>
        </div>

        {/* Meta bar */}
        <div className="px-6 sm:px-10 py-3 bg-white/[0.02] border-b border-white/10 flex items-center gap-4 text-zinc-400">
          <div className="flex items-center gap-1.5">
            <FileText size={11} className="text-zinc-400" />
            <span className="text-[9px] font-bold text-zinc-400 uppercase tracking-wider">Full Document View</span>
          </div>
          <div className="h-3 w-px bg-white/10" />
          <span className="text-[9px] text-zinc-400 font-medium uppercase">
            {new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}
          </span>
          <div className="ml-auto flex items-center gap-1.5">
            <div className="w-1.5 h-1.5 rounded-full bg-emerald-400" />
            <span className="text-[9px] font-bold text-zinc-300 uppercase tracking-wider">Servex US</span>
          </div>
        </div>

        {/* Cuerpo del Reporte */}
        <div className="p-6 sm:p-10 lg:p-14">
          <div className="prose prose-invert max-w-none
            prose-headings:text-white prose-headings:font-bold
            prose-h2:text-base prose-h2:border-b prose-h2:border-white/10 prose-h2:pb-3 prose-h2:mt-8
            prose-h3:text-[13px] prose-h3:text-zinc-200
            prose-p:text-zinc-300 prose-p:leading-relaxed prose-p:text-[12px]
            prose-strong:text-white prose-strong:font-bold
            prose-li:text-zinc-300">
            <ReactMarkdown
              remarkPlugins={[remarkGfm]}
              components={{
                table: ({node, ...props}) => (
                  <div className="my-6 overflow-hidden rounded-xl border border-white/10 shadow-lg bg-white/[0.02]">
                    <table className="min-w-full divide-y divide-white/5" {...props} />
                  </div>
                ),
                thead: ({node, ...props}) => <thead className="bg-[#121215]/95 backdrop-blur-sm border-b border-white/10" {...props} />,
                th: ({node, ...props}) => (
                  <th className="px-5 py-3.5 text-left text-[10px] font-bold text-zinc-300 uppercase tracking-widest border-b border-white/10" {...props} />
                ),
                tr: ({node, ...props}) => <tr className="hover:bg-white/[0.04] transition-all duration-200 group cursor-default" {...props} />,
                td: ({node, ...props}) => (
                  <td className="px-5 py-3 text-[12px] text-zinc-300 border-t border-white/5 transition-colors group-hover:text-white" {...props} />
                ),
                blockquote: ({node, ...props}) => (
                  <div className="bg-white/[0.03] border-l-4 border-white/30 px-5 py-4 my-6 text-[12px] italic text-zinc-300 rounded-r-xl">
                    {props.children}
                  </div>
                )
              }}
            >
              {agentData}
            </ReactMarkdown>
          </div>
        </div>

        {/* Footer */}
        <div className="bg-white/[0.02] border-t border-white/10 p-5 px-6 sm:px-10 flex justify-between items-center text-[9px] text-zinc-400 font-bold uppercase tracking-[0.15em]">
          <div className="flex items-center gap-3">
            <div className="w-1.5 h-1.5 bg-emerald-400 rounded-full" />
            <p>Powered by <span className="text-white">Servex_AI Core Logic</span></p>
          </div>
          <div className="flex gap-6 items-center opacity-70">
            <div className="hidden sm:flex items-center gap-1.5">
              <Shield size={10} />
              <span>Azure OAuth 2.0</span>
            </div>
            <div className="flex items-center gap-1.5">
              <Cloud size={10} />
              <span>SVX_PROD</span>
            </div>
          </div>
        </div>
      </div>

      <style>{`
        @keyframes fadeInUp {
          from { opacity: 0; transform: translateY(16px); }
          to   { opacity: 1; transform: translateY(0); }
        }
      `}</style>
    </div>
  );
};

export default AgentInfo;